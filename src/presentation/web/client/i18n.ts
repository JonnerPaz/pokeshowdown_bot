export function detectLanguage(languageCode: string | undefined): Language {
  return languageCode?.toLowerCase().startsWith("es") ? "es" : "en";
}

export function createTranslator(language: Language): Translator {
  const dictionary = dictionaries[language];

  return (key, params) => {
    let value = dictionary[key] ?? en[key];
    if (params) {
      for (const [name, replacement] of Object.entries(params)) {
        value = value.replace(`{${name}}`, String(replacement));
      }
    }
    return value;
  };
}

export function translateError(t: Translator, code: string): string {
  const key = ERROR_KEYS[code];
  return key ? t(key) : t("noticeError");
}
